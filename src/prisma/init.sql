CREATE TABLE IF NOT EXISTS "Restaurant" (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  address TEXT,
  category TEXT NOT NULL DEFAULT 'restaurant',
  "googlePlaceId" TEXT,
  "googleReviewUrl" TEXT,
  slug TEXT,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "Restaurant_googlePlaceId_key" UNIQUE ("googlePlaceId"),
  CONSTRAINT "Restaurant_slug_key" UNIQUE (slug)
);

ALTER TABLE "Restaurant" ADD COLUMN IF NOT EXISTS "googleReviewUrl" TEXT;
ALTER TABLE "Restaurant" ADD COLUMN IF NOT EXISTS category TEXT NOT NULL DEFAULT 'restaurant';
ALTER TABLE "Restaurant" ADD COLUMN IF NOT EXISTS "ownerEmail" TEXT;

CREATE TABLE IF NOT EXISTS "Review" (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rating INTEGER NOT NULL,
  comment TEXT,
  "authorName" TEXT,
  "cuisineRating" INTEGER,
  "serviceRating" INTEGER,
  "ambianceRating" INTEGER,
  "visitMonth" INTEGER,
  "visitYear" INTEGER,
  "restaurantId" INTEGER NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "Review_restaurantId_fkey" FOREIGN KEY ("restaurantId") REFERENCES "Restaurant"(id)
);

